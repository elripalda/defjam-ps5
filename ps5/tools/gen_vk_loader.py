#!/usr/bin/env python3
"""[ps5 port] Write the Vulkan entry points the program calls, as functions
that forward to RADV, which is linked into the app (there is no loader on the
PS5). Every vk* name used in the given sources that vulkan_core.h declares
gets a definition that looks itself up once through RADV's
vk_icdGetInstanceProcAddr.

    gen_vk_loader.py <vulkan_core.h> <out.c> <source>...
"""
import re
import sys

GLOBAL = {'vkCreateInstance', 'vkEnumerateInstanceExtensionProperties',
          'vkEnumerateInstanceLayerProperties', 'vkEnumerateInstanceVersion'}
SKIP = {'vkGetInstanceProcAddr'}  # written by hand below


def main():
    header, out, sources = sys.argv[1], sys.argv[2], sys.argv[3:]
    text = open(header).read()
    protos = {}
    for m in re.finditer(r'VKAPI_ATTR\s+([\w\s\*]+?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\)\s*;', text, re.S):
        ret, name, args = m.group(1).strip(), m.group(2), ' '.join(m.group(3).split())
        protos[name] = (ret, args)
    used = set()
    for s in sources:
        used |= set(re.findall(r'\b(vk[A-Z]\w*)\b', open(s, errors='replace').read()))
    used.add('vkGetDeviceProcAddr')
    names = sorted(n for n in used if n in protos and n not in SKIP)

    o = ['/* Generated by ps5/tools/gen_vk_loader.py; do not edit. */',
         '#include <stdio.h>', '#include <stdlib.h>', '#include <string.h>',
         '#include <vulkan/vulkan.h>', '',
         'extern VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vk_icdGetInstanceProcAddr(VkInstance, const char *) __attribute__((weak));',
         'static VkInstance s_instance;', '',
         'static PFN_vkVoidFunction ps5_vk_resolve(const char *name, int global)',
         '{',
         '    PFN_vkVoidFunction fn = vk_icdGetInstanceProcAddr(global ? NULL : s_instance, name);',
         '    if (!fn) {',
         '        /* RADV exports some core 1.1+ commands only under their KHR names. */',
         '        char alt[128];',
         '        snprintf(alt, sizeof alt, "%sKHR", name);',
         '        fn = vk_icdGetInstanceProcAddr(global ? NULL : s_instance, alt);',
         '    }',
         '    if (!fn)',
         '        fprintf(stderr, "[VK] RADV has no %s\\n", name);',
         '    return fn;',
         '}', '',
         'VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vkGetInstanceProcAddr(VkInstance instance, const char *name)',
         '{',
         '    PFN_vkVoidFunction fn = vk_icdGetInstanceProcAddr(instance, name);',
         '    if (!fn && name) {',
         '        char alt[128];',
         '        snprintf(alt, sizeof alt, "%sKHR", name);',
         '        fn = vk_icdGetInstanceProcAddr(instance, alt);',
         '    }',
         '    return fn;',
         '}', '']
    for n in names:
        ret, args = protos[n]
        params = [] if args.strip() == 'void' else [a.strip() for a in args.split(',')]
        argnames = [re.findall(r'(\w+)\s*(?:\[[^\]]*\])?$', p)[0] for p in params]
        call = ', '.join(argnames)
        g = 1 if n in GLOBAL else 0
        o.append(f'VKAPI_ATTR {ret} VKAPI_CALL {n}({args})')
        o.append('{')
        o.append(f'    static PFN_{n} fn;')
        o.append(f'    if (!fn) fn = (PFN_{n})ps5_vk_resolve("{n}", {g});')
        if n == 'vkCreateInstance':
            o.append(f'    VkResult r = fn({call});')
            o.append('    if (r == VK_SUCCESS) s_instance = *pInstance;')
            o.append('    return r;')
        elif ret == 'void':
            o.append(f'    fn({call});')
        else:
            o.append(f'    return fn({call});')
        o.append('}')
        o.append('')
    open(out, 'w').write('\n'.join(o))
    print(f'{len(names)} Vulkan entry points')


if __name__ == '__main__':
    main()
